class question_generator {
    /** @var string[] Text mimetypes that can be read directly from file contents. */
    const TEXT_MIMETYPES = ['text/plain', 'text/html', 'text/csv'];

    /**
     * Creates an instance of the question_generator.
     */
    public function __construct(
        /** @var int The id of the context the question_generator is called from. */
        private readonly int $contextid
    ) {
    }

    /**
     * Returns the default template for the system prompt.
     *
     * The system prompt tells the LLM how to behave in general. The only conditional part is the
     * {{#sendexistingquestions}} block. Supported placeholders: {{primer}}, {{instructions}}, {{example}},
     * {{existingquestionsjson}} and the conditional block {{#sendexistingquestions}}...{{/sendexistingquestions}}.
     *
     * @return string the default system prompt template
     */
    public static function get_default_system_prompt(): string {
        return <<<'EOT'
## PRIMER
{{primer}}

## INSTRUCTIONS
{{instructions}}

## EXAMPLE MOODLE XML QUESTION
{{example}}

{{#sendexistingquestions}}
## ALREADY EXISTING QUESTIONS
The question that will be generated by you has to be as different as possible
from all of the following questions in this JSON string:
{{existingquestionsjson}}
{{/sendexistingquestions}}
EOT;
    }

    /**
     * Returns the default user message template for the "topic" mode.
     *
     * In this mode the LLM is asked to generate a question about a topic using its own training data.
     * Supported placeholder: {{story}}.
     *
     * @return string the default user message template for topic mode
     */
    public static function get_default_usermessage_topic(): string {
        return <<<'EOT'
## QUESTION GENERATION MODE - TOPIC
Create a question about the following topic. Use your own training data to generate it:
{{story}}
EOT;
    }

    /**
     * Returns the default user message template for the "content" mode.
     *
     * In this mode the LLM is asked to generate a question from the provided content (either pasted content or
     * content extracted from course activities) and must not use its own training data.
     * Supported placeholder: {{story}}.
     *
     * @return string the default user message template for content mode
     */
    public static function get_default_usermessage_content(): string {
        return <<<'EOT'
## QUESTION GENERATION MODE - CONTENTS
Create a question from the following contents. Only use this contents and do not use any training data:
### START OF USER PROVIDED CONTENT
{{story}}
### END OF USER PROVIDED CONTENT
EOT;
    }

    /**
     * Renders the system prompt template.
     *
     * The conditional {{#sendexistingquestions}}...{{/sendexistingquestions}} block is resolved by a regular expression:
     * If $sendexistingquestions is true, only the block markers are removed, otherwise the whole block is removed.
     * Afterwards the values (primer, instructions, example, existingquestionsjson) are substituted verbatim
     * by {@see self::substitute_placeholders()}.
     *
     * @param string $template the system prompt template
     * @param bool $sendexistingquestions whether the existing questions block should be included
     * @param array $values associative array of scalar placeholder values
     *  (keys: primer, instructions, example, existingquestionsjson)
     * @return string the rendered system prompt
     */
    public static function render_system_prompt(string $template, bool $sendexistingquestions, array $values): string {
        $template = preg_replace(
            '/{{#sendexistingquestions}}(.*?){{\/sendexistingquestions}}/s',
            $sendexistingquestions ? '$1' : '',
            $template
        );
        return self::substitute_placeholders($template, $values);
    }

    /**
     * Substitutes {{key}} placeholders in a string with the given values.
     *
     * strtr replaces all placeholders in a single pass, so the values are inserted verbatim without any escaping,
     * and placeholders contained in a value are not replaced again.
     *
     * @param string $template the template string containing {{key}} placeholders
     * @param array $values associative array mapping placeholder names to their replacement values
     * @return string the string with all placeholders replaced
     */
    public static function substitute_placeholders(string $template, array $values): string {
        $replacements = [];
        foreach ($values as $key => $value) {
            $replacements['{{' . $key . '}}'] = $value;
        }
        return strtr($template, $replacements);
    }

    /**
     * Generate a question by using an external LLM.
     *
     * @param stdClass $dataobject of the stored processing data from qbank_questiongen DB table extended with example data.
     * @return stdClass|string object containing information about the generated question or string containing an error message
     *  in case of an error occurred and no question could be generated
     */
    public function generate_question(stdClass $dataobject, bool $sendexistingquestionsascontext): stdClass|string {
        global $CFG, $DB;
        require_once($CFG->dirroot . '/question/engine/bank.php');

        $primer = $dataobject->primer;
        $story = $dataobject->story;
        $instructions = $dataobject->instructions;
        $example = $dataobject->example;

        $errormessage = '';
        $generatedquestiontext = '';
        $systemprompt = '';
        $usermessage = '';

        $provider = get_config('qbank_questiongen', 'provider');
        if ($provider === 'local_ai_manager') {
            $systemprompttemplate = get_config('qbank_questiongen', 'systemprompt');

            $existingquestionsjson = '';
            if ($sendexistingquestionsascontext) {
                $questionidsincategory = question_bank::get_finder()->get_questions_from_categories(
                    [$dataobject->category],
                    null
                );
                if (!empty($questionidsincategory)) {
                    [$insql, $inparams] = $DB->get_in_or_equal($questionidsincategory);
                    $rs = $DB->get_recordset_select('question', "id $insql", $inparams);
                    $questiontextsinqbankcat = [];
                    foreach ($rs as $record) {
                        $questiontextsinqbankcat[] = [
                            'title' => $record->name,
                            'question_text' => strip_tags($record->questiontext),
                        ];
                    }
                    $rs->close();
                    $existingquestionsjson = json_encode($questiontextsinqbankcat);
                }
            }

            $systemprompt = self::render_system_prompt(
                $systemprompttemplate,
                !empty($existingquestionsjson),
                [
                    'primer' => $primer,
                    'instructions' => $instructions,
                    'example' => $example,
                    'existingquestionsjson' => $existingquestionsjson,
                ]
            );

            // Select the user message template depending on the generation mode. Topic mode lets the LLM use its own
            // training data, whereas story/course contents mode restricts the LLM to the provided content.
            if ($dataobject->mode === story_form::QUESTIONGEN_MODE_TOPIC) {
                $usermessagetemplate = get_config('qbank_questiongen', 'usermessagetopic');
            } else {
                $usermessagetemplate = get_config('qbank_questiongen', 'usermessagecontent');
            }
            $usermessage = self::substitute_placeholders($usermessagetemplate, ['story' => $story]);

            $messages = [
                [
                    'sender' => 'system',
                    'message' => $systemprompt,
                ],
                [
                    'sender' => 'user',
                    'message' => $usermessage,
                ],
            ];

            [
                'generatedquestiontext' => $generatedquestiontext,
                'errormessage' => $errormessage,
            ] = $this->retrieve_llm_response($messages);
        }

        if (!empty($errormessage)) {
            return $errormessage;
        }

        // We return a whole question object containing all the generated data. This can be used for unit tests or logging.
        $question = new stdClass();
        $question->example = $example;
        $question->instructions = $instructions;
        $question->primer = $primer;
        $question->systemprompt = $systemprompt;
        $question->usermessage = $usermessage;
        $question->text = $generatedquestiontext;

        return $question;
    }

    /**
     * Generates the story to send to the LLM based on the content from course activites.
     *
     * @param array $courseactivities list of course module ids
     * @return string text extracted from the activities that can be send as context to the external AI system
     */
    public function create_story_from_cms(array $courseactivities): string {
        global $CFG;
        require_once($CFG->dirroot . '/question/editlib.php');

        [, $firstcm] = get_module_from_cmid(reset($courseactivities));
        $modinfo = get_fast_modinfo($firstcm->course);
        $story = '';
        $cms = array_filter($modinfo->get_cms(), fn($cm) => in_array($cm->id, $courseactivities));

        foreach ($cms as $cm) {
            if (!in_array($cm->id, $courseactivities)) {
                continue;
            }
            if (!$this->is_cm_supported($cm)) {
                debugging('Course module with id ' . $cm->id . ' is currently not supported');
                continue;
            }
            $story .= $this->extract_content_from_cm($cm);
        }
        return $story;
    }

    /**
     * Returns if a course module is supported by the question generator.
     *
     * @param cm_info $cm the cm_info object of the course module
     * @return bool true if extracting content from the course module is supported, false otherwise
     */
    public static function is_cm_supported(cm_info $cm): bool {
        if (in_array($cm->modname, ['page', 'label', 'lesson', 'book', 'folder'])) {
            return true;
        }
        if ($cm->modname === 'resource') {
            $context = \context_module::instance($cm->id);
            $fs = get_file_storage();
            $files = $fs->get_area_files($context->id, 'mod_resource', 'content', 0, 'sortorder DESC, id ASC', false);
            $file = reset($files);
            if (empty($file)) {
                return false;
            }
            $extractor = \core\di::get(\local_ai_content\document_extractor::class);
            return $extractor->is_file_supported($file);
        }
        return false;
    }

    /**
     * For a given course module, extract the content as plain text.
     *
     * @param cm_info $cm the cm_info object of the course module
     * @return string the content of the course module as plain text.
     * @throws \coding_exception if the course module is not supported
     */
    public function extract_content_from_cm(cm_info $cm): string {
        global $CFG, $DB;
        // TODO Eventually also respect course module descriptions and title?
        $content = '';
        $instance = $cm->get_instance_record();
        switch ($cm->modname) {
            case 'page':
                $content = $instance->content;
                break;
            case 'label':
                $content = $instance->intro;
                break;
            case 'resource':
                $context = \context_module::instance($cm->id);
                $fs = get_file_storage();
                $files = $fs->get_area_files($context->id, 'mod_resource', 'content', 0, 'sortorder DESC, id ASC', false);
                $file = reset($files);
                if (!empty($file)) {
                    $content = $this->extract_content_from_file($file);
                }
                break;
            case 'folder':
                $context = \context_module::instance($cm->id);
                $fs = get_file_storage();
                $files = $fs->get_area_files($context->id, 'mod_folder', 'content', 0, 'id ASC', false);
                $filecontents = [];
                foreach ($files as $file) {
                    if (!empty($file)) {
                        $filecontent = trim($this->extract_content_from_file($file));
                        if ($filecontent !== '') {
                            $filecontents[] = $filecontent;
                        }
                    }
                }
                // Will later be converted to proper line breaks.
                $content = implode("<br/><br/>", $filecontents);
                break;
            case 'lesson':
                require_once($CFG->dirroot . '/mod/lesson/locallib.php');
                $lesson = lesson::load($instance->id);
                $pages = $lesson->load_all_pages();
                $pagescontents = [];
                foreach ($pages as $page) {
                    // We must not use $page->get_contents() here because it requires having the $PAGE object set up properly for
                    // the lesson course module which we do not have.
                    $pagescontents[] = trim($page->properties()->contents);
                }
                $content = implode("<br/><br/>", $pagescontents);
                break;
            case 'book':
                require_once($CFG->dirroot . '/mod/book/locallib.php');
                $book = $DB->get_record('book', ['id' => $instance->id]);
                $chapters = book_preload_chapters($book);
                $chaptercontents = [];
                foreach ($chapters as $chapter) {
                    $chaptercontents[] = $chapter->title . "<br/>" . $chapter->content;
                }
                $content = implode("<br/><br/>", $chaptercontents);
                break;
            default:
                throw new \coding_exception('Unsupported course module/course module type - cmid: ' . $cm->id . ', ' .
                    $cm->modname);
        }

        return empty($content) ? '' : self::format_extracted_cm_content($content);
    }

    /**
     * Extracts content from pdf or image files.
     *
     * Delegates extraction to local_ai_content\document_extractor.
     *
     * @param \stored_file $file The file to send
     * @return string the extracted content as text
     */
    public function extract_content_from_pdf_or_image(\stored_file $file): string {
        $extractor = \core\di::get(\local_ai_content\document_extractor::class);
        return $extractor->extract_text_from_file($file, $this->contextid, $file->get_userid() ?: null, 'qbank_questiongen');
    }

    /**
     * Extract content from a file.
     *
     * Extraction failures propagate to the caller.
     *
     * @param \stored_file $file The file to process.
     * @return string The extracted content.
     */
    private function extract_content_from_file(\stored_file $file): string {
        if (in_array($file->get_mimetype(), self::TEXT_MIMETYPES)) {
            return $file->get_content();
        }

        $extractor = \core\di::get(\local_ai_content\document_extractor::class);
        try {
            return $extractor->extract_text_from_file($file, $this->contextid, $file->get_userid() ?: null, 'qbank_questiongen');
        } catch (\moodle_exception $exception) {
            throw new questiongen_exception(
                $exception->errorcode,
                $exception->module,
                $exception->link,
                $exception->a,
                $exception->debuginfo
            );
        }
    }

    /**
     * Helper function to format the extracted content.
     *
     * It basically removes all HTML tags and converts line breaks into text line breaks.
     *
     * @param string $content the content to format
     * @return string the formatted content
     */
    public static function format_extracted_cm_content(string $content): string {
        $content = trim($content);
        return html_to_text($content, 0, false);
    }

    /**
     * Helper function to retrieve the generated question XML from the external LLM.
     *
     * @param array $messages a standardized messages array containing the "conversation" with the LLM
     * @return string[] array with keys 'generatedquestionxml' and 'errormessage'. If 'errormessage' is empty retrieving
     *  was successful, otherwise it contains an error message.
     */
    public function retrieve_llm_response(array $messages): array {
        // TODO Implement different backend(s). It's only local_ai_manager for now.
        $return = [
            'generatedquestiontext' => '',
            'errormessage' => '',
        ];
        $manager = new \local_ai_manager\manager('questiongeneration');
        $lastmessage = array_pop($messages);
        $result = $manager->perform_request(
            $lastmessage['message'],
            'qbank_questiongen',
            $this->contextid,
            ['conversationcontext' => $messages]
        );
        if ($result->get_code() === 200) {
            $return['generatedquestiontext'] = $result->get_content();
            mtrace('Question generation successful. The external LLM returned: ');
            mtrace($result->get_content());
        } else {
            mtrace('Question generation failed. The external LLM returned code ' . $result->get_code() . ':');
            mtrace($result->get_errormessage());
            if (!empty($result->get_debuginfo())) {
                mtrace($result->get_debuginfo());
            }
            // Return the error message.
            $result['errormessage'] = $result->get_errormessage();
        }
        return $return;
    }
}
